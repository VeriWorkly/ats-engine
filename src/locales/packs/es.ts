/**
 * Spanish (Español), for Spain and Latin America. Built around three traits:
 * - Accents come and go on an English keyboard ("Educacion", "ingles"), so headings, months and
 *   level words take both spellings.
 * - Bullets open with a past verb ("Desarrollé…") or a noun ("Desarrollo de…"); both count as
 *   action verbs.
 * - Place names in English resumes are Spanish ("Los Angeles", "Las Vegas", "El Paso", "San
 *   Jose"), so no article, "de", "del" or "san" is a detection word.
 * Credentials that differ by country (bachillerato, ciclo formativo, TSU) belong to the region
 * packs; the words every Spanish-speaking country uses for a degree are here.
 */
